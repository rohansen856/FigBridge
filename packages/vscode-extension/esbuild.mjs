// Bundles the extension to dist/extension.js (CommonJS) and copies runtime assets.
import { writeNotices } from '../../scripts/notices.mjs';
import { build, context } from 'esbuild';
import { cpSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const production = process.argv.includes('--production');
const watch = process.argv.includes('--watch');

function copyAssets() {
  const wasmOut = 'dist/wasm';
  mkdirSync(wasmOut, { recursive: true });
  const coreDir = dirname(require.resolve('@figbridge/core/package.json'));
  const coreRequire = createRequire(join(coreDir, 'package.json'));
  const vscodeWasm = join(dirname(coreRequire.resolve('@vscode/tree-sitter-wasm/package.json')), 'wasm');
  const runtime = join(dirname(coreRequire.resolve('web-tree-sitter')), 'web-tree-sitter.wasm');
  cpSync(runtime, join(wasmOut, 'web-tree-sitter.wasm'));
  for (const g of ['typescript', 'tsx', 'javascript']) cpSync(join(vscodeWasm, `tree-sitter-${g}.wasm`), join(wasmOut, `tree-sitter-${g}.wasm`));
  cpSync(join(coreDir, 'wasm', 'tree-sitter-dart.wasm'), join(wasmOut, 'tree-sitter-dart.wasm'));
  // Claude Code plugin marketplace (built by packages/claude).
  const marketplace = join(dirname(require.resolve('@figbridge/claude/package.json')), 'marketplace');
  cpSync(marketplace, 'claude-marketplace', { recursive: true });
  // Manifest JSON Schema for the YAML extension (generated by the core build).
  mkdirSync('schemas', { recursive: true });
  cpSync(join(coreDir, '..', '..', 'schemas', 'figma.design.schema.json'), 'schemas/figma.design.schema.json');
}

const options = {
  entryPoints: ['src/extension.ts'],
  bundle: true,
  outfile: 'dist/extension.js',
  format: 'cjs',
  platform: 'node',
  target: 'node20',
  external: ['vscode'],
  sourcemap: !production,
  minify: production,
  // core is ESM and uses import.meta.url; provide it in the CommonJS bundle.
  define: { 'import.meta.url': 'importMetaUrl' },
  banner: { js: "const importMetaUrl = require('url').pathToFileURL(__filename).href;" },
  logLevel: 'info',
  metafile: true,
};

if (watch) {
  const ctx = await context(options);
  await ctx.watch();
} else {
  const result = await build(options);
  const coreDir = dirname(require.resolve('@figbridge/core/package.json'));
  const dart = { name: 'tree-sitter-dart (grammar, compiled to WASM)', version: '1.0.0', license: 'MIT', dir: join(coreDir, 'wasm'), licenseFile: 'tree-sitter-dart.LICENSE' };
  const vsWasm = createRequire(join(coreDir, 'package.json')).resolve('@vscode/tree-sitter-wasm/package.json');
  const grammars = { name: '@vscode/tree-sitter-wasm (TypeScript/TSX/JavaScript grammars)', version: '0.3.1', license: 'MIT', dir: dirname(vsWasm) };
  writeNotices(result.metafile, 'THIRD_PARTY_NOTICES.md', [dart, grammars]);
}
try {
  copyAssets();
} catch (e) {
  console.error('asset copy failed:', e.message);
  process.exitCode = 1;
}
